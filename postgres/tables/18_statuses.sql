-- =====================================================================
-- app.statuses - Configuration > Statuses: the invoice workflow statuses.
-- app.invoices.status references statuses.code (ON UPDATE CASCADE), so renaming a
-- code updates existing invoices and a status in use cannot be deleted.
-- The four core statuses are system data (inserted here, not in seed.sql).
-- Depends on: app.invoices
-- Idempotent: creates the table when missing; the UPGRADES section brings
-- existing databases up to date. Run through deploy_schema.sql.
-- =====================================================================
CREATE TABLE IF NOT EXISTS app.statuses (
    id          integer GENERATED BY DEFAULT AS IDENTITY CONSTRAINT pk_statuses PRIMARY KEY,
    code        varchar(20)     NOT NULL CONSTRAINT uq_statuses_code UNIQUE,  -- value stored in invoices.status
    name        varchar(150)    NOT NULL,                       -- label shown in the UI
    description varchar(500)    NULL,
    color       varchar(20)     NULL,                           -- pill style: warning | info | success | danger | neutral
    sort_order  integer         NOT NULL DEFAULT 0,
    is_active   boolean         NOT NULL DEFAULT true,
    created_at  timestamptz(0)  NOT NULL DEFAULT now(),
    updated_at  timestamptz(0)  NOT NULL DEFAULT now()
);

CREATE UNIQUE INDEX IF NOT EXISTS uq_statuses_name ON app.statuses (lower(name));

-- Core workflow statuses (required by existing invoices)
INSERT INTO app.statuses (code, name, description, color, sort_order) VALUES
    ('Pending',   'Pending',   'Received, waiting for review',  'warning', 10),
    ('Approved',  'Approved',  'Reviewed and approved',         'success', 20),
    ('Processed', 'Processed', 'Posted for payment',            'info',    30),
    ('Rejected',  'Rejected',  'Rejected during review',        'danger',  40)
ON CONFLICT (code) DO NOTHING;

-- Invoices now validate their status against this table instead of a fixed CHECK list
ALTER TABLE app.invoices DROP CONSTRAINT IF EXISTS ck_invoices_status;
DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_invoices_status') THEN
        ALTER TABLE app.invoices
            ADD CONSTRAINT fk_invoices_status FOREIGN KEY (status) REFERENCES app.statuses (code) ON UPDATE CASCADE;
    END IF;
END $$;

