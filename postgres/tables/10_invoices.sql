-- =====================================================================
-- app.invoices - Invoices list, Create / Bulk upload, Invoice Detail header
-- Depends on: app.app_modules, app.vendors, app.country_stations, app.users
-- Idempotent: creates the table when missing; the UPGRADES section brings
-- existing databases up to date. Run through deploy_schema.sql.
-- =====================================================================
CREATE TABLE IF NOT EXISTS app.invoices (
    id                          integer GENERATED BY DEFAULT AS IDENTITY CONSTRAINT pk_invoices PRIMARY KEY,
    invoice_code                varchar(60)     NOT NULL CONSTRAINT uq_invoices_code UNIQUE,   -- public id, e.g. INV-GP-1015
    module_id                   integer         NOT NULL CONSTRAINT fk_invoices_module  REFERENCES app.app_modules (id),
    vendor_id                   integer         NOT NULL CONSTRAINT fk_invoices_vendor  REFERENCES app.vendors (id),
    station_id                  integer         NULL     CONSTRAINT fk_invoices_station REFERENCES app.country_stations (id),
    invoice_1a                  varchar(30)     NULL,           -- "1a Invoice" column
    invoice_2a                  varchar(30)     NULL,           -- "2a Invoice" column
    first_invoice_number        varchar(20)     NULL,           -- 1° Invoice Number (point of sale)
    second_invoice_number       varchar(20)     NULL,           -- 2° Invoice Number
    invoice_date                date            NULL,
    expiry_days                 integer         NULL,
    invoice_expiry_date         timestamptz(0)  NULL,
    support_team                boolean         NOT NULL DEFAULT false,
    pre_settlement_number       varchar(30)     NULL,
    credit_note                 boolean         NOT NULL DEFAULT false,
    currency_code               char(3)         NOT NULL DEFAULT 'ARS',
    amount                      numeric(18,2)   NOT NULL CONSTRAINT ck_invoices_amount CHECK (amount >= 0),
    invoice_subtotal            numeric(18,2)   NULL,
    invoice_subtotal_with_tax   numeric(18,2)   NULL,
    status                      varchar(20)     NOT NULL DEFAULT 'Pending'
                                CONSTRAINT ck_invoices_status CHECK (status IN ('Pending', 'Approved', 'Processed', 'Rejected')),
    reception_date              date            NOT NULL,
    email_reception_date        timestamptz(0)  NULL,
    created_by                  integer         NULL CONSTRAINT fk_invoices_created_by REFERENCES app.users (id),
    created_at                  timestamptz(0)  NOT NULL DEFAULT now(),
    updated_at                  timestamptz(0)  NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS ix_invoices_module_status   ON app.invoices (module_id, status) INCLUDE (reception_date, amount);
CREATE INDEX IF NOT EXISTS ix_invoices_module_received ON app.invoices (module_id, reception_date DESC);
CREATE INDEX IF NOT EXISTS ix_invoices_vendor          ON app.invoices (vendor_id);

