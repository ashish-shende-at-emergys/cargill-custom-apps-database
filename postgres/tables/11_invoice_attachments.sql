-- =====================================================================
-- app.invoice_attachments - invoice PDFs and supporting documents
-- Files live under the backend storage root (STORAGE_DIR); storage_path is relative to it.
-- Depends on: app.invoices
-- Idempotent: creates the table when missing; the UPGRADES section brings
-- existing databases up to date. Run through deploy_schema.sql.
-- =====================================================================
CREATE TABLE IF NOT EXISTS app.invoice_attachments (
    id              integer GENERATED BY DEFAULT AS IDENTITY CONSTRAINT pk_invoice_attachments PRIMARY KEY,
    invoice_id      integer         NOT NULL CONSTRAINT fk_attachments_invoice REFERENCES app.invoices (id) ON DELETE CASCADE,
    file_name       varchar(255)    NOT NULL,
    title           varchar(255)    NULL,
    category        varchar(50)     NOT NULL,                       -- Invoice Document, Tax Document, Manifest
    mime_type       varchar(100)    NOT NULL DEFAULT 'application/pdf',
    size_bytes      bigint          NULL,
    storage_path    varchar(500)    NOT NULL,
    is_primary      boolean         NOT NULL DEFAULT false,
    uploaded_at     timestamptz(0)  NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS ix_invoice_attachments_invoice ON app.invoice_attachments (invoice_id);
-- At most one primary PDF per invoice
CREATE UNIQUE INDEX IF NOT EXISTS ux_invoice_attachments_primary ON app.invoice_attachments (invoice_id) WHERE is_primary;

