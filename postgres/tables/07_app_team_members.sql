-- =====================================================================
-- app.app_team_members - team access list per module (Admin Configuration)
-- Depends on: app.app_modules, app.teams, app.users
-- Idempotent: creates the table when missing; the UPGRADES section brings
-- existing databases up to date. Run through deploy_schema.sql.
-- =====================================================================
CREATE TABLE IF NOT EXISTS app.app_team_members (
    id          integer GENERATED BY DEFAULT AS IDENTITY CONSTRAINT pk_app_team_members PRIMARY KEY,
    module_id   integer         NOT NULL CONSTRAINT fk_team_members_module REFERENCES app.app_modules (id) ON DELETE CASCADE,
    team_id     integer         NOT NULL CONSTRAINT fk_team_members_team   REFERENCES app.teams (id),
    user_id     integer         NULL     CONSTRAINT fk_team_members_user   REFERENCES app.users (id),
    name        varchar(200)    NOT NULL,
    email       varchar(255)    NOT NULL,
    alias       varchar(100)    NOT NULL,
    created_at  timestamptz(0)  NOT NULL DEFAULT now()
);

CREATE UNIQUE INDEX IF NOT EXISTS uq_team_members ON app.app_team_members (module_id, lower(email));

